def auto_width(text: str, minimum: int = 12, maximum: int = 56) -> int:
    lines = text.splitlines() or [text]
    line_max = max(len(line) for line in lines)
    return max(minimum, min(maximum, line_max + 2))


def wrap_for_cell(items: list[str]) -> str:
    return "\n".join(f"- {item}" for item in items)


