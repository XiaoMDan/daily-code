def daterange(start: date, end: date) -> list[date]:
    items = []
    cursor = start
    while cursor <= end:
        items.append(cursor)
        cursor += timedelta(days=1)
    return items


def validate_days() -> None:
    expected = [d.isoformat() for d in daterange(START_DATE, END_DATE)]
    actual = [item["date"] for item in DAYS]
    if actual != expected:
        missing = sorted(set(expected) - set(actual))
        extras = sorted(set(actual) - set(expected))
        raise ValueError(f"Date coverage mismatch. Missing={missing}, extras={extras}")


def format_weekday(day_str: str) -> str:
    weekday_map = ["周一", "周二", "周三", "周四", "周五", "周六", "周日"]
    dt = datetime.strptime(day_str, "%Y-%m-%d").date()
    return weekday_map[dt.weekday()]


